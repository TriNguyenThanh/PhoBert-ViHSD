        "        self.html_pattern = re.compile(r'<.*?>')",
        "        self.whitespace_pattern = re.compile(r'\\s+')",
        "",
        "        # Nhận diện ký tự chữ cái lặp lại từ 3 lần trở lên bao gồm cả bảng chữ cái tiếng Việt",
        "        self.lengthening_pattern = re.compile(",
