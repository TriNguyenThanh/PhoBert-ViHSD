        "    raw_eff = 1.0 / effective_num",
        "    w_effective = (raw_eff / np.sum(raw_eff)) * num_classes",
        "",
        "    return {",
        "        'icf': torch.tensor(w_icf, dtype=torch.float32),",
        "        'smoothed': torch.tensor(w_smoothed, dtype=torch.float32),",
