        "",
        "# Hàm tính toán vector trọng số phân bố lớp trên tập huấn luyện",
        "def compute_class_weights_dict(labels, beta=0.999):",
        "    \"\"\"Tính toán vector trọng số phân bố lớp theo 3 phương pháp khác nhau.\"\"\"",
        "    labels = np.asarray(labels, dtype=int)",
        "    total_samples = len(labels)",
        "    classes, counts = np.unique(labels, return_counts=True)",
        "    num_classes = len(classes)",
        "    counts_float = counts.astype(np.float64)",
        "",
        "    # 1. Phương pháp ICF (Inverse Class Frequency)",
        "    w_icf = total_samples / (num_classes * counts_float)",
        "",
        "    # 2. Phương pháp làm mịn căn bậc hai (Smoothed Inverse Frequency)",
        "    raw_smoothed = np.sqrt(total_samples / counts_float)",
        "    w_smoothed = raw_smoothed / np.mean(raw_smoothed)",
        "",
        "    # 3. Phương pháp số lượng mẫu hiệu dụng (Effective Number of Samples)",
