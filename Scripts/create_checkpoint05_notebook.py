        "                transformed_texts.append(cleaned_text)",
        "                valid_indices.append(idx)",
        "",
        "        filtered_df = df_clean.loc[valid_indices].copy()",
        "        X = transformed_texts",
        "        y = filtered_df[label_col].to_numpy()",
        "",
        "        return X, y"
